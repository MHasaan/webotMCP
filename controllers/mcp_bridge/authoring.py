"""Pure authoring helpers: world-file / script / PROTO / CSV generation and
lighting presets. No Webots (`controller`) imports, so unit-testable standalone.

Used by the bridge (script export, proto extraction, record CSV) and the server
(world templates, backups). All emit plain text / plain data.
"""

import re

WEBOTS_HEADER = "#VRML_SIM R2025a utf8"


# ---------------------------------------------------------------------------
# World templates (8.6)
# ---------------------------------------------------------------------------

LIGHTING_PRESETS = {
    "indoor": {"sky": [0.6, 0.62, 0.65],
               "lights": [{"type": "DirectionalLight", "direction": [-0.5, -0.5, -1],
                           "intensity": 2.0, "castShadows": True}]},
    "outdoor": {"sky": [0.4, 0.6, 0.9],
                "lights": [{"type": "DirectionalLight", "direction": [1, -1, -3],
                            "intensity": 3.5, "castShadows": True}]},
    "studio": {"sky": [0.9, 0.9, 0.9],
               "lights": [{"type": "DirectionalLight", "direction": [-1, -0.5, -1],
                           "intensity": 2.5, "castShadows": False},
                          {"type": "DirectionalLight", "direction": [1, 0.5, -1],
                           "intensity": 1.5, "castShadows": False}]},
    "night": {"sky": [0.02, 0.02, 0.05],
              "lights": [{"type": "DirectionalLight", "direction": [-0.3, -0.3, -1],
                          "intensity": 0.4, "castShadows": True}]},
}


def lighting_preset(preset):
    if preset not in LIGHTING_PRESETS:
        raise ValueError(f"unknown lighting preset {preset!r}; "
                         f"choose from {sorted(LIGHTING_PRESETS)}")
    return LIGHTING_PRESETS[preset]


def _light_node(spec, intensity=None):
    it = intensity if intensity is not None else spec.get("intensity", 1.0)
    d = spec.get("direction", [0, 0, -1])
    return (f'DirectionalLight {{ direction {d[0]} {d[1]} {d[2]} '
            f'intensity {it} castShadows {"TRUE" if spec.get("castShadows") else "FALSE"} }}')


def world_template_wbt(name="world", template="empty", size=10.0,
                       coordinate_system="ENU", lighting="indoor"):
    """Generate a valid R2025a .wbt using base nodes only (no EXTERNPROTO needed).
    Templates: 'empty' (floor only), 'indoor_room' (floor + 4 walls),
    'outdoor_flat' (large floor)."""
    if template not in ("empty", "indoor_room", "outdoor_flat"):
        raise ValueError(f"unknown template {template!r}")
    half = size / 2.0
    preset = lighting_preset(lighting)
    sky = preset["sky"]
    lines = [WEBOTS_HEADER,
             f"WorldInfo {{ coordinateSystem \"{coordinate_system}\" basicTimeStep 32 }}",
             f"Viewpoint {{ position {size} {-size} {size * 0.8} "
             f"orientation 0.3 0.3 0.88 2.0 }}",
             f"Background {{ skyColor [ {sky[0]} {sky[1]} {sky[2]} ] }}"]
    for spec in preset["lights"]:
        lines.append(_light_node(spec))
    floor_size = size * 2 if template == "outdoor_flat" else size
    lines.append(
        f'DEF FLOOR Solid {{ translation 0 0 0 children [ '
        f'Shape {{ appearance PBRAppearance {{ baseColor 0.8 0.8 0.8 roughness 1 }} '
        f'geometry DEF FLOOR_GEO Plane {{ size {floor_size} {floor_size} }} }} ] '
        f'boundingObject USE FLOOR_GEO name "floor" }}')
    if template == "indoor_room":
        wall_h = 2.0
        t = 0.1
        walls = [(0, half, [size, t, wall_h]), (0, -half, [size, t, wall_h]),
                 (half, 0, [t, size, wall_h]), (-half, 0, [t, size, wall_h])]
        for i, (x, y, dim) in enumerate(walls):
            lines.append(
                f'DEF WALL_{i} Solid {{ translation {x} {y} {wall_h / 2} children [ '
                f'Shape {{ appearance PBRAppearance {{ baseColor 0.9 0.9 0.85 }} '
                f'geometry DEF WG_{i} Box {{ size {dim[0]} {dim[1]} {dim[2]} }} }} ] '
                f'boundingObject USE WG_{i} name "wall_{i}" }}')
    return "\n".join(lines) + "\n"


