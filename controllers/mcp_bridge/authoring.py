def python_script_from_nodes(node_strings, header_comment=""):
    """A standalone Supervisor controller that rebuilds the given nodes via
    importMFNodeFromString on the scene root."""
    body = ['"""Auto-generated by webotMCP generate_world_script.',
            header_comment, '"""',
            "from controller import Supervisor",
            "",
            "sup = Supervisor()",
            "root = sup.getRoot().getField('children')",
            "",
            "NODES = ["]
    for s in node_strings:
        body.append("    " + repr(s) + ",")
    body += ["]", "",
             "for node_string in NODES:",
             "    root.importMFNodeFromString(-1, node_string)",
             "",
             "timestep = int(sup.getBasicTimeStep())",
             "while sup.step(timestep) != -1:",
             "    pass"]
    return "\n".join(body) + "\n"


def json_scenario_from_objects(objects, physics=None, conditions=None,
                               duration_s=None):
    """Declarative scenario dict: object list (+ optional node_string), physics,
    success/failure conditions, duration."""
    scenario = {"version": 1, "objects": objects}
    if physics:
        scenario["physics"] = physics
    if conditions:
        scenario["conditions"] = conditions
    if duration_s is not None:
        scenario["duration_s"] = duration_s
    return scenario


