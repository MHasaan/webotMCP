def records_to_csv(rows, columns):
    """rows: list of dicts; columns: ordered list of keys. Returns CSV text."""
    out = [",".join(columns)]
    for r in rows:
        out.append(",".join(_csv_cell(r.get(c, "")) for c in columns))
    return "\n".join(out) + "\n"


def _csv_cell(v):
    if isinstance(v, (list, tuple)):
        v = " ".join(str(x) for x in v)
    s = str(v)
    if "," in s or '"' in s or "\n" in s:
        return '"' + s.replace('"', '""') + '"'
    return s


def cad_shape_node_string(url, name="cad", physics=False, bounding_box=None,
                          position=(0, 0, 0)):
    """A Solid wrapping a CadShape that renders an .obj/.dae mesh. Optional axis-
    aligned Box boundingObject ([x,y,z]) and Physics for a dynamic object."""
    x, y, z = position
    # VRML strings treat '\' as an escape; use forward slashes so Windows paths
    # (C:\Users\...) don't corrupt the url ("Invalid escaped character").
    url = str(url).replace("\\", "/")
    parts = [f'Solid {{ translation {x} {y} {z} name "{name}" '
             f'children [ CadShape {{ url [ "{url}" ] }} ]']
    if bounding_box:
        b = bounding_box
        parts.append(f'boundingObject Box {{ size {b[0]} {b[1]} {b[2]} }}')
    if physics:
        parts.append("physics Physics { }")
    parts.append("}")
    return " ".join(parts)


def supervisor_script_scaffold(name, code=""):
    """A standalone Supervisor controller with robust node/field helpers matching
    the bridge, ready to run at full speed as an extern controller."""
    return (f'"""Supervisor automation script \'{name}\' (webotMCP scaffold)."""\n'
            "from controller import Supervisor, Field\n\n"
            "sup = Supervisor()\n"
            "timestep = int(sup.getBasicTimeStep())\n\n"
            "def node(ref):\n"
            "    n = sup.getFromDef(ref)\n"
            "    if n is None:\n"
            "        try:\n"
            "            n = sup.getFromId(int(ref))\n"
            "        except (TypeError, ValueError):\n"
            "            n = None\n"
            "    if n is None:\n"
            "        raise ValueError('node not found: %r' % (ref,))\n"
            "    return n\n\n"
            "def field(ref, name):\n"
            "    return node(ref).getField(name)\n\n"
            "# ---- user code ----\n"
            f"{code}\n")


def extern_controller_command(exe, controller_path, robot=None, protocol=None,
                              port=None, extra_args=None):
    """Build the webots-controller launcher argv. Only includes flags that are
    provided (robot-name, protocol, port). A .py controller is passed directly so
    webots-controller wires up PYTHONPATH and runs it with the system Python."""
    cmd = [str(exe)]
    if robot:
        cmd.append(f"--robot-name={robot}")
    if protocol:
        cmd.append(f"--protocol={protocol}")
    if port:
        cmd.append(f"--port={port}")
    cmd.append(str(controller_path))
    if extra_args:
        cmd.extend(str(a) for a in extra_args)
    return cmd


def summarize_series(rows, value_key):
    """min/max/mean of a numeric column across rows (ignoring missing)."""
    vals = [r[value_key] for r in rows if isinstance(r.get(value_key), (int, float))]
    if not vals:
        return None
    return {"min": round(min(vals), 5), "max": round(max(vals), 5),
            "mean": round(sum(vals) / len(vals), 5), "count": len(vals)}
