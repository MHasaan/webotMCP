_SF_FIELD_TYPES = {"translation": "SFVec3f", "rotation": "SFRotation",
                   "name": "SFString"}
_DEFAULTS = {"translation": "0 0 0", "rotation": "0 0 1 0", "name": '"solid"'}


def wrap_proto(node_string, proto_name, expose=("translation", "rotation", "name")):
    """Wrap an exported node string as a reusable PROTO exposing the listed SF
    fields (translation/rotation/name) as parameters via IS. Returns the .proto
    text. Fields not present in the node are still exposed with sensible
    defaults so the PROTO is always instantiable."""
    if not re.match(r"^[A-Za-z_]\w*$", proto_name):
        raise ValueError("proto_name must be a valid identifier")
    body = node_string.strip()
    # strip a leading DEF so the PROTO body is a bare node
    body = re.sub(r"^DEF\s+\w+\s+", "", body)
    fields = []
    for f in expose:
        ftype = _SF_FIELD_TYPES.get(f)
        if ftype is None:
            continue
        m = re.search(rf"\b{f}\s+([^\n]+?)\s+(?=[A-Za-z]+\s|\]|\}}|$)", body)
        default = _DEFAULTS[f]
        if f == "name":
            mn = re.search(r'\bname\s+"([^"]*)"', body)
            if mn:
                default = f'"{mn.group(1)}"'
        elif m:
            default = m.group(1).strip()
        fields.append(f"  field {ftype} {f} {default}")
        # rewrite occurrences to IS
        if f == "name":
            body = re.sub(r'\bname\s+"[^"]*"', "name IS name", body, count=1)
        else:
            # match the field name + its whitespace-separated numeric values
            # (handles scientific notation like 7.3e-17 without splitting on 'e'
            # and without swallowing the following field/newline).
            num = r"[-+]?\d*\.?\d+(?:[eE][-+]?\d+)?"
            body = re.sub(rf"\b{f}(?:\s+{num})+",
                          f"{f} IS {f}", body, count=1)
    # ensure the exposed fields exist in the body (inject if missing)
    for f in expose:
        if f in _SF_FIELD_TYPES and f"{f} IS {f}" not in body:
            body = re.sub(r"\{", f"{{ {f} IS {f}", body, count=1)
    header = [WEBOTS_HEADER, f"PROTO {proto_name} ["] + fields + ["]", "{", body, "}"]
    return "\n".join(header) + "\n"


